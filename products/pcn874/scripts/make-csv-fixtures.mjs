#!/usr/bin/env node
/**
 * Regenerate tests/fixtures/csv/*.csv — the generator's INPUTS.
 *
 * Same discipline as `make-fixtures.mjs`, which builds the validator's fixed-width
 * fixtures: nothing is hand-typed into the repository. The column names come from
 * `GENERATOR_COLUMNS` in `src/generate.ts`, so a renamed column breaks this script
 * rather than silently rotting a fixture, and every digit below is invented.
 *
 * These files are inputs to a generator, not filings. `minimal.csv` is built to
 * reproduce `tests/fixtures/valid-minimal.txt` byte for byte, which is the golden
 * test: the generator and the hand-built fixture have to agree on the same file.
 *
 * Run:  node scripts/make-csv-fixtures.mjs
 */

import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const outDir = join(here, '..', 'tests', 'fixtures', 'csv');

/**
 * The canonical column order. Kept in step with `GENERATOR_COLUMNS` by
 * `tests/generate.test.ts`, which compares the two lists.
 */
const COLUMNS = [
  'entryType',
  'counterpartyVatId',
  'invoiceDate',
  'refGroup',
  'refNumber',
  'vatSum',
  'invoiceSum',
  'allocationNumber',
  'inputKind',
];

const DEALER = '514457282';

const quote = value => {
  const text = String(value ?? '');
  return /[",\r\n]/.test(text) ? `"${text.replace(/"/g, '""')}"` : text;
};

/**
 * @param {Record<string, string|number|undefined>} meta the "# key: value" block
 * @param {readonly Record<string, string|number|undefined>[]} rows one per document
 * @param {readonly string[]} [comments] free comment lines, written first
 */
function csv(meta, rows, comments = []) {
  const lines = [];
  for (const comment of comments) lines.push(`# ${comment}`);
  for (const [key, value] of Object.entries(meta)) {
    if (value === undefined) continue;
    lines.push(`# ${key}: ${value}`);
  }
  lines.push(COLUMNS.join(','));
  for (const row of rows) lines.push(COLUMNS.map(c => quote(row[c])).join(','));
  return `${lines.join('\n')}\n`;
}

