// The PCN874 rule reference on pcn874.html, generated from the validator's own
// rule table (TikTok note N10).
//
// RULES in products/pcn874/src/validate.ts (vendored in src/vendor/pcn874/) is
// the one place a check's severity and citations live: the validator builds
// every finding from it, and pcn874's tests/rules.test.ts proves every row is
// reported and every finding equals its row. This module turns that table into
// a section of the page - each check as an error or a warning, the lines of the
// circular it cites, a plain Hebrew explanation (the same wording the page uses
// for a finding, from pcn874-report.js), then what is not checked.
//
// The section is committed inside pcn874.html between two markers, so the page
// served locally and the tests see it. scripts/pcn874-rule-reference.js writes
// it; scripts/build-site.js refuses to build, preview too, when the committed
// section differs from what this module renders. So the page cannot describe a
// rule the tool does not run, or miss one it does.
//
// Build-time only. No shipped page imports this module, so it does not ship.
import { RULES, basisOf } from '../vendor/pcn874/validate.js';
import { kindOf } from '../vendor/pcn874/sources.js';
import { SEVERITY_HE, ruleHebrew, fieldRuleHebrew, REPRESENTATIVE_INITIAL_HE } from './pcn874-report.js';

export const RULE_REFERENCE_START =
  '<!-- pcn874-rule-reference:start - generated by scripts/pcn874-rule-reference.js from the validator\'s rule table; do not edit here -->';
export const RULE_REFERENCE_END = '<!-- pcn874-rule-reference:end -->';

/**
 * Hebrew for each variant the table names (a rule id reported two ways). Keyed
 * by the validator's own English label, so a new or renamed variant has no
 * Hebrew here and the tests turn red.
 */
export const VARIANT_HE = Object.freeze({
  'both amounts zero': 'כששני הסכומים ברשומה הם אפס',
  'invoice total zero, VAT not zero': 'כשרק סכום החשבונית הוא אפס וסכום המע״מ אינו אפס',
  'above 5,000 shekels before VAT': 'מעל 5,000 ש״ח לפני מע״מ',
  'at or below 5,000 shekels before VAT, or unreadable': 'עד 5,000 ש״ח לפני מע״מ, או כשהסכום אינו קריא',
  'an "A" record: the initial entry of a representatives\' file (Appendix B)':
    "רשומה שמתחילה ב-A: רשומת הפתיחה של קובץ מייצגים (נספח ב')",
  'any other first character': 'כל תו ראשון אחר',
  'a "Z" closing entry: the summary entry of a representatives\' file (Appendix B)':
    "רשומת סגירה שמתחילה ב-Z: רשומת הסיכום של קובץ מייצגים (נספח ב')",
  'any other value': 'כל ערך אחר',
});

/** Rows whose variant is explained by a text other than the id's own. */
const VARIANT_EXPLANATION = {
  'file.record.unknown|an "A" record: the initial entry of a representatives\' file (Appendix B)': () => REPRESENTATIVE_INITIAL_HE,
  'footer.recordType.literal|any other value': () => fieldRuleHebrew('footer.recordType.literal'),
};

/** What the validator does not check, after the rules (docs/SPEC.md §7.1 "No rule at all", and the page's scope box). */
export const NOT_CHECKED_HE = Object.freeze([
  'סכומים: הבודק אינו מצליב את הסכומים שבכותרת מול סכום הרשומות, ואינו מחשב את הסכום המדווח (<span dir="ltr">reportedVat</span>), כי החוזר אינו קובע לו נוסחה.',
  'תאריך החשבונית: נבדק רק שיש בו 8 ספרות – לא שהוא תאריך קיים ולא שהוא בתוך תקופת הדיווח.',
  'ספרת הביקורת של מספרי העוסק.',
  'מספר הקצאה: שדה מספר ההקצאה מתקבל גם כשהוא אפסים, ואין כלל על הסכום שממנו חשבונית חייבת מספר הקצאה.',
  'שם הקובץ.',
  "קובץ מייצגים (נספח ב'), שמייצג מגיש בשם כמה עוסקים: אינו נבדק כלל.",
]);

const GROUPS = [
  { prefix: 'file', title: 'מבנה הקובץ' },
  { prefix: 'header', title: 'רשומת הכותרת (O)' },
  { prefix: 'detail', title: 'רשומות הפירוט: עסקאות ותשומות' },
  { prefix: 'footer', title: 'רשומת הסגירה (X)' },
  { prefix: 'totals', title: 'הכותרת מול הרשומות' },
];

const lineOf = (citation) => citation.slice(citation.lastIndexOf(':') + 1);
const dash = (range) => range.replace('-', '–');

function linesHe(lines, sources) {
  if (lines.length) return `${lines.length === 1 && !lines[0].includes('-') ? 'שורה' : 'שורות'} ${lines.map(dash).join(', ')}`;
  return basisOf(sources) === 'vendor-manual'
    ? 'אין שורה בחוזר; הכלל נשען על מדריך של ספק תוכנה'
    : 'אין שורה בחוזר; הכלל נשען על מימושים בקוד פתוח בלבד';
}

/**
 * One row per row of RULES, in the table's order.
 *
 * @returns {{id: string, variant: string|undefined, variantHe: string|null, severity: string, severityHe: string,
 *   lines: string[], linesHe: string, explanation: string}[]}
 */
export function ruleReferenceRows() {
  return RULES.map((rule) => {
    const lines = rule.sources.filter((s) => kindOf(s) === 'official').map(lineOf);
    const special = rule.variant ? VARIANT_EXPLANATION[`${rule.id}|${rule.variant}`] : undefined;
    return {
      id: rule.id,
      variant: rule.variant,
      variantHe: rule.variant ? (VARIANT_HE[rule.variant] ?? null) : null,
      severity: rule.severity,
      severityHe: SEVERITY_HE[rule.severity] ?? rule.severity,
      lines,
      linesHe: linesHe(lines, rule.sources),
      explanation: special ? special() : ruleHebrew(rule.id, { severity: rule.severity }),
    };
  });
}

const escape = (text) => String(text).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

/** The section, markers included, as it sits in pcn874.html. */
export function renderRuleReference() {
  const rows = ruleReferenceRows();
  for (const row of rows) {
    if (!GROUPS.some((g) => row.id.startsWith(`${g.prefix}.`))) throw new Error(`pcn874 rule ${row.id} has no group on the page`);
    if (row.variant && !row.variantHe) throw new Error(`pcn874 rule ${row.id}: no Hebrew for its variant "${row.variant}"`);
    if (!row.explanation) throw new Error(`pcn874 rule ${row.id}: no Hebrew explanation`);
  }
  const errors = rows.filter((r) => r.severity === 'error').length;
  const warnings = rows.filter((r) => r.severity === 'warning').length;
  const anchored = new Set();

  const out = [
    RULE_REFERENCE_START,
    '<section class="card no-print" id="pcn-rules" aria-labelledby="pcn-rules-title">',
    '  <h2 id="pcn-rules-title">כל הכללים שהבודק בודק</h2>',
    `  <p>הרשימה נוצרת מטבלת הכללים של הבודק עצמו, והאתר אינו נבנה כשהיא אינה תואמת לה – כך שהיא מתארת בדיוק את מה שהבודק מריץ. בסך הכול ${rows.length} כללים: ${errors} שגיאות ו-${warnings} אזהרות. כלל שמדווח בשני אופנים מופיע בשתי שורות ונספר פעמיים, והשורה אומרת באיזה מקרה.</p>`,
    '  <p class="note">מספרי השורות הם של הטקסט שחולץ מקובץ ה-PDF של החוזר (הנוסח האנגלי שבאתר רשות המסים), ולא של עמודי ה-PDF. שגיאה היא הפרה של כלל שהחוזר קובע במפורש; אזהרה היא מקום שהחוזר אינו מכריע בו, או שאין לו בחוזר מקור כלל.</p>',
  ];
  for (const group of GROUPS) {
    const inGroup = rows.filter((r) => r.id.startsWith(`${group.prefix}.`));
    if (!inGroup.length) continue;
    out.push(
      `  <details><summary>${escape(group.title)} (${inGroup.length})</summary>`,
      '    <div class="table-scroll">',
      '      <table class="data-table">',
      `        <caption>${escape(group.title)}: כל כלל, חומרתו, השורות בחוזר שהוא נשען עליהן, והסבר.</caption>`,
      '        <thead><tr><th scope="col">הכלל</th><th scope="col">חומרה</th><th scope="col">בחוזר</th><th scope="col">הסבר</th></tr></thead>',
      '        <tbody>',
    );
    for (const row of inGroup) {
      const anchor = anchored.has(row.id) ? '' : ` id="rule-${row.id}"`;
      anchored.add(row.id);
      const variant = row.variantHe ? `<br><span class="note">${escape(row.variantHe)}</span>` : '';
      out.push(
        `          <tr${anchor}><td><code dir="ltr">${row.id}</code>${variant}</td><td>${row.severityHe}</td><td>${escape(row.linesHe)}</td><td>${escape(row.explanation)}</td></tr>`,
      );
    }
    out.push('        </tbody>', '      </table>', '    </div>', '  </details>');
  }
  out.push('  <h3>מה הבודק אינו בודק</h3>', '  <ul>');
  for (const item of NOT_CHECKED_HE) out.push(`    <li>${item}</li>`);
  out.push('  </ul>', '</section>', RULE_REFERENCE_END);
  return `${out.join('\n')}\n`;
}

function markers(html) {
  const start = html.indexOf(RULE_REFERENCE_START);
  const end = html.indexOf(RULE_REFERENCE_END);
  if (start < 0 || end < start) return null;
  let after = end + RULE_REFERENCE_END.length;
  if (html[after] === '\n') after += 1;
  return { start, after };
}

/** The page with its rule reference regenerated. Throws when the page has no markers for it. */
export function withRuleReference(html) {
  const at = markers(html);
  if (!at) throw new Error('pcn874.html has no rule-reference markers');
  return html.slice(0, at.start) + renderRuleReference() + html.slice(at.after);
}

/** Why the committed rule reference is not what the validator's table gives; empty when it is. */
export function ruleReferenceProblems(html) {
  const at = markers(html);
  if (!at) return ['pcn874.html has no rule-reference section (its start and end markers are missing)'];
  if (html.slice(at.start, at.after) !== renderRuleReference()) {
    return ["the rule reference in pcn874.html differs from the validator's rule table"];
  }
  return [];
}
