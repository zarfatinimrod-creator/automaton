export const meta = {
  name: 'fable-owner-docs-judgement',
  description: 'Fable queue item 2: one Fable refuter rules on the 26 JUDGEMENT findings in the owner documents; separate Opus editors apply only what it confirms',
  phases: [
    { title: 'Probe', detail: 'one-word Fable call; stop here if the quota is still out' },
    { title: 'Judge', detail: 'one Fable refuter over all 26 JUDGEMENT findings (research/owner-docs-audit/APPLIED.md)' },
    { title: 'Edit', detail: 'one Opus editor per document, applies only CONFIRMED edits, never re-judges' },
  ],
}

// The Opus half of this audit ran on 25.9 (wf_a170db68-c5f, wf_f3c464ed-d34): 131 mechanical findings
// were confirmed and applied. The 26 left are JUDGEMENT — a forecast, an outside-world fact, or two
// repo documents disagreeing — which the model rule gives to Fable. One Fable agent rules on all of
// them (a fan-out on Fable is how the quota died before); Opus editors apply the result, because
// separating the judge from the editor is what kept the Opus half honest.

const ROOT = '/home/user/automaton'

const DOCS = {
  'docs/OWNER_STEPS.he.md': 'npx vitest run src/__tests__/revenue/owner-steps.test.ts',
  'docs/INCOME_PLAN.he.md': 'npx vitest run src/__tests__/revenue',
  'products/README.md': 'npx vitest run src/__tests__/revenue',
  'products/apify-il-open-data/docs/PUBLISH.md': '',
  'products/il-biz-tools/README.md': '',
  'products/pcn874/README.md': '',
  'products/x402-il-api/README.md': '',
  'products/mcp-il-tools/README.md': '',
}

const JUDGE_SCHEMA = {
  type: 'object',
  properties: {
    results: {
      type: 'array',
      items: {
        type: 'object',
        properties: {
          doc: { type: 'string', description: 'repo-relative path, exactly as in the APPLIED.md table' },
          line: { type: 'number' },
          verdict: { type: 'string', enum: ['CONFIRMED', 'REFUTED', 'OWNER_QUESTION'] },
          reasoning: { type: 'string' },
          evidence: { type: 'string', description: 'path:line, rendered page, or command + output' },
          oldText: { type: 'string', description: 'CONFIRMED only: exact, unique substring of the document at HEAD' },
          newText: { type: 'string', description: 'CONFIRMED only: minimal replacement, same language and register' },
          codeChange: { type: 'string', description: 'when the fix belongs in code or data, what and where; else empty' },
          ownerQuestion: { type: 'string', description: 'OWNER_QUESTION only: the one question, in Hebrew, answerable in a sentence' },
        },
        required: ['doc', 'line', 'verdict', 'reasoning', 'evidence', 'oldText', 'newText', 'codeChange', 'ownerQuestion'],
      },
    },
    reportPath: { type: 'string' },
  },
  required: ['results', 'reportPath'],
}

const EDIT_SCHEMA = {
  type: 'object',
  properties: {
    doc: { type: 'string' },
    applied: { type: 'array', items: { type: 'object', properties: { line: { type: 'number' }, summary: { type: 'string' } }, required: ['line', 'summary'] } },
    skipped: { type: 'array', items: { type: 'object', properties: { line: { type: 'number' }, reason: { type: 'string' } }, required: ['line', 'reason'] } },
    testCommand: { type: 'string' },
    testResult: { type: 'string' },
  },
  required: ['doc', 'applied', 'skipped', 'testCommand', 'testResult'],
}

phase('Probe')
const probe = await agent('Reply with the single word OK and nothing else.', { label: 'probe', phase: 'Probe', model: 'fable' })
if (!probe) {
  log('Fable did not answer the probe; nothing else ran. Re-run this script when the quota renews.')
  return { blocked: 'fable-quota' }
}

phase('Judge')
const judged = await agent([
  'You are the FABLE REFUTER for the owner-facing documents of the revenue colony (repo ' + ROOT + '). These are the files the owner acts on; a wrong sentence here sends a real person to do a wrong thing, or promises money that will not come.',
  'Read ' + ROOT + '/MISSION.md in full first (it binds you), then ' + ROOT + '/research/owner-docs-audit/APPLIED.md. Its section "Queued for Fable (JUDGEMENT) ..." lists the findings; rule on EVERY row whose Kind/verdict is JUDGEMENT/NEEDS_FABLE (26 rows) and on nothing else — the MECHANICAL rows there are already handled in code. Each row names the document, the line, the claim, and an Opus refuter\'s evidence. Open the document at that line yourself; the file changed since (124 mechanical edits landed), so find the sentence by its text.',
  'For each finding decide: CONFIRMED (the document is wrong, overstated or misleading as the owner will read it) with the smallest correction; REFUTED (the sentence stands as written); OWNER_QUESTION only when the truth is a preference only the owner holds (rare — a forecast is not a preference).',
  'state/colony/REPORT.md is GENERATED by scripts/colony.ts report from state/colony/colony.db and src/revenue/*; for a CONFIRMED finding there leave oldText/newText empty and describe the source change in codeChange.',
  'How to rule: (1) a forecast may stay in an owner document only labelled as an estimate with its basis, and never above the audited figures in src/revenue/portfolio.ts and research/colony-sweep/BOARD.md / CHIEF-AUDIT.md — where an older plan and a later board ruling disagree, the later ruling wins unless you can show it is wrong. (2) An outside-world fact (a policy, a URL, a simulator, a platform rule) stands only if a rendered page (research/rendered/*.txt) or source code supports it; otherwise soften it to what is known and say so. (3) A sentence that implies an owner action not in docs/OWNER_STEPS.he.md / src/revenue/owner-steps.ts is CONFIRMED wrong: the mandate is that the owner does nothing recurring. (4) newText may state only what your evidence shows; same language and register as the document (Hebrew for the owner, code identifiers in English).',
  'You may use at most 3 WebSearch calls (ToolSearch "select:WebSearch" first), only for an outside-world fact no repo file settles; a snippet alone never makes a claim true.',
  'Write your reasoning to ' + ROOT + '/research/owner-docs-audit/JUDGEMENT.md (English; one short section per finding: document:line, verdict, why, evidence), then return the structured result. Edit no other file; never run git.',
].join('\n'), { label: 'judge', phase: 'Judge', schema: JUDGE_SCHEMA, model: 'fable' })

if (!judged) return { blocked: 'judge-failed' }

phase('Edit')
const byDoc = {}
for (const r of judged.results) {
  if (r.verdict !== 'CONFIRMED' || !r.oldText || !r.newText || !(r.doc in DOCS)) continue
  ;(byDoc[r.doc] = byDoc[r.doc] || []).push({ line: r.line, oldText: r.oldText, newText: r.newText })
}

const edits = await parallel(Object.keys(byDoc).map((doc) => () => agent([
  'You are the EDITOR for one document the owner acts on. A Fable refuter (a different agent) has already judged each finding; you do NOT re-judge. Apply exactly the CONFIRMED edits below and nothing else.',
  'Document: ' + ROOT + '/' + doc + '. Edit ONLY this file. Never run git. Never regenerate docs/OWNER_STEPS.he.pdf (the main thread does that).',
  'For each edit: find oldText verbatim in the current file; if it is present exactly once, replace it with newText using the Edit tool; if it is missing or ambiguous, skip it and say why. Keep the file\'s formatting.',
  DOCS[doc] ? 'After editing, run: cd ' + ROOT + ' && ' + DOCS[doc] + ' - and report the result line. If a test fails because of one of your edits, revert that edit and report it as skipped with the failing assertion.' : 'No test guards this file; report testCommand and testResult as "none".',
  'CONFIRMED edits (JSON):',
  JSON.stringify(byDoc[doc], null, 1),
  'Return the structured result only.',
].join('\n'), { label: 'edit:' + doc.split('/').slice(-2).join('/'), phase: 'Edit', schema: EDIT_SCHEMA, model: 'opus' })))

const tally = {}
for (const r of judged.results) tally[r.verdict] = (tally[r.verdict] || 0) + 1
log('verdicts: ' + JSON.stringify(tally))
return { tally, judged, edits: edits.filter(Boolean), codeChanges: judged.results.filter((r) => r.codeChange) }
